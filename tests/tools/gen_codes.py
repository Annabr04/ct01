#!/usr/bin/env python3
"""Generate include/ct01/codes.hpp (DESIGN v0.3.4 Appendix A, frozen, append-only).

Source of truth: tests/spec/codes_tables_v0_3_4.py (imported read-only). The script ALSO
parses DESIGN.md Appendix A (A.1 FAIL-reason table, A.2 code/reason table) and refuses to generate
if the two disagree.
  gen_codes.py --write   regenerate the header
  gen_codes.py --check   exit 1 if the checked-in header differs (CTest codes_vs_design)
"""
import importlib.util, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SPEC = ROOT / "tests/spec/codes_tables_v0_3_4.py"
DESIGN = ROOT / "DESIGN.md"
OUT = ROOT / "include/ct01/codes.hpp"


def load_spec():
    spec = importlib.util.spec_from_file_location("codes_tables_v0_3_4", SPEC)
    m = importlib.util.module_from_spec(spec)
    sys.dont_write_bytecode = True   # never write __pycache__ into the spec dir
    spec.loader.exec_module(m)
    return m


def parse_design():
    text = DESIGN.read_text()
    i = text.index("## Appendix A. codes.hpp")
    app = text[i:]
    a1 = app[app.index("A.1"):app.index("A.2")]
    fail = {}
    for row in a1.splitlines():
        cells = [c.strip() for c in row.strip().strip("|").split("|")]
        for k in range(0, len(cells) - 1, 2):
            if cells[k].isdigit() and cells[k + 1].startswith("e_"):
                fail[int(cells[k])] = cells[k + 1]
    codes = {}
    a2 = app[app.index("A.2"):]
    for row in a2.splitlines():
        m = re.match(r"^\| (\d+) \| (GENESIS|EVENT|CHECKPOINT|EPOCH_START) \| (\w+) \| ([^|]*) \|", row)
        if not m:
            continue
        rt = {"GENESIS": 1, "EVENT": 2, "CHECKPOINT": 3, "EPOCH_START": 4}[m.group(2)]
        reasons = {}
        for part in m.group(4).split(","):
            v, n = part.strip().split(" ", 1)
            reasons[int(v)] = n.strip()
        codes[int(m.group(1))] = (rt, m.group(3), reasons)
    return fail, codes


def generate(m):
    fr = m.FAIL_REASONS
    L = []
    w = L.append
    w("// GENERATED by tests/tools/gen_codes.py from tests/spec/codes_tables_v0_3_4.py, cross-checked")
    w("// against DESIGN.md v0.3.4 Appendix A. DO NOT EDIT. Numbers FROZEN at M0 (A011 F66): never")
    w("// renumbered, append only. CTest codes_vs_design fails if this file drifts.")
    w("#pragma once")
    w("")
    w("#include <array>")
    w("#include <cstddef>")
    w("#include <cstdint>")
    w("#include <string_view>")
    w("")
    w("namespace ct01::audit {")
    w("")
    w("// A.1 FAIL reasons (JSON `reason`; GENESIS.count for GENESIS reason 3). 0 = e_none.")
    w("enum class Reason : std::uint8_t {")
    w("    none = 0,  // e_none")
    for i, n in enumerate(fr[1:], 1):
        w(f"    {n} = {i},")
    w(f"    count_ = {len(fr)}")
    w("};")
    w(f"inline constexpr std::array<std::string_view, {len(fr)}> kReasonNames{{{{")
    for i in range(0, len(fr), 6):
        w("    " + " ".join(f'"{n}",' for n in fr[i:i + 6]))
    w("}};")
    w(f"inline constexpr std::uint16_t kFailReasonMax = {len(fr) - 1};")
    w("")
    w("namespace codes {")
    w("struct ReasonValue { std::uint16_t value; std::string_view name; };")
    w("struct CodeTable {")
    w("    std::uint16_t code;")
    w("    std::uint8_t rec_type;   // 1 GENESIS, 2 EVENT, 3 CHECKPOINT, 4 EPOCH_START")
    w("    std::string_view name;")
    w("    const ReasonValue* reasons;")
    w("    std::size_t reason_count;")
    w("};")
    w("namespace code {")
    for c, (rt, n, r) in sorted(m.CODES.items()):
        w(f"inline constexpr std::uint16_t {n} = {c};")
    w("}  // namespace code")
    w("namespace reason {   // per-code reason values: reason::<code name>::<reason name>")
    for c, (rt, n, r) in sorted(m.CODES.items()):
        vals = ", ".join(f"{rn} = {v}" for v, rn in sorted(r.items()))
        w(f"namespace {n} {{ inline constexpr std::uint16_t {vals}; }}")
    w("}  // namespace reason")
    for c, (rt, n, r) in sorted(m.CODES.items()):
        vals = ", ".join(f'{{{v}, "{rn}"}}' for v, rn in sorted(r.items()))
        w(f"inline constexpr ReasonValue kReasons_{c}[] = {{{vals}}};")
    w(f"inline constexpr std::array<CodeTable, {len(m.CODES)}> kCodeTables{{{{")
    for c, (rt, n, r) in sorted(m.CODES.items()):
        w(f'    {{{c}, {rt}, "{n}", kReasons_{c}, {len(r)}}},')
    w("}};")
    w("inline constexpr const CodeTable* find_code(std::uint16_t c) {")
    w("    for (const auto& t : kCodeTables)")
    w("        if (t.code == c) return &t;")
    w("    return nullptr;")
    w("}")
    w("// Any reason value not listed for the code = e_reason.")
    w("inline constexpr bool reason_allowed(std::uint16_t c, std::uint16_t reason) {")
    w("    const CodeTable* t = find_code(c);")
    w("    if (!t) return false;")
    w("    for (std::size_t i = 0; i < t->reason_count; ++i)")
    w("        if (t->reasons[i].value == reason) return true;")
    w("    return false;")
    w("}")
    w("inline constexpr std::string_view reason_value_name(std::uint16_t c, std::uint16_t reason) {")
    w("    const CodeTable* t = find_code(c);")
    w("    if (t)")
    w("        for (std::size_t i = 0; i < t->reason_count; ++i)")
    w("            if (t->reasons[i].value == reason) return t->reasons[i].name;")
    w('    return "unknown";')
    w("}")
    w("// FAULT-raising records (valid targets of 69 reason 1 fault), A.2; plus any EVENT with dmethod 4.")
    w("inline constexpr bool is_fault_raising(std::uint16_t c, std::uint16_t reason, bool dmethod_keyed_failed) {")
    w("    if (dmethod_keyed_failed) return true;")
    w("    switch (c) {")
    by = {}
    for c, r in m.FAULT_RAISING:
        by.setdefault(c, set()).add(r)
    for c in sorted(by):
        rs = by[c]
        if None in rs:
            w(f"        case {c}: return true;")
        else:
            w(f"        case {c}: return " + " || ".join(f"reason == {v}" for v in sorted(rs)) + ";")
    w("        default: return false;")
    w("    }")
    w("}")
    w("}  // namespace codes")
    w("}  // namespace ct01::audit")
    return "\n".join(L) + "\n"


def main():
    m = load_spec()
    fail, codes = parse_design()
    ok = True
    if fail != dict(enumerate(m.FAIL_REASONS)):
        print("MISMATCH: DESIGN A.1 vs codes_tables FAIL_REASONS"); ok = False
    if codes != m.CODES:
        for c in sorted(set(codes) | set(m.CODES)):
            if codes.get(c) != m.CODES.get(c):
                print(f"MISMATCH code {c}: DESIGN {codes.get(c)} vs spec {m.CODES.get(c)}")
        ok = False
    if not ok:
        return 1
    out = generate(m)
    if "--write" in sys.argv:
        OUT.write_text(out)
        print(f"wrote {OUT.relative_to(ROOT)}: {len(m.FAIL_REASONS)} FAIL reasons, {len(m.CODES)} codes")
        return 0
    if OUT.read_text() != out:
        print("codes.hpp differs from the generator output (run gen_codes.py --write)")
        return 1
    print(f"codes.hpp matches DESIGN Appendix A and codes_tables_v0_3_4.py: {len(m.FAIL_REASONS)} FAIL reasons, {len(m.CODES)} codes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
